// Les traductions des fonctionnalités d'engagement vivent dans un fichier à part, fusionné ici.
export const translations: Record<Language, Messages & FeatureMessages> = {
  fr: { ...fr, ...featureTranslations.fr },
  en: { ...en, ...featureTranslations.en },
  ar: { ...ar, ...featureTranslations.ar },
};

export function isLanguage(value: unknown): value is Language {
  return value === 'fr' || value === 'en' || value === 'ar';
}

export function translate(language: Language, key: string, vars?: Record<string, string | number>): string {
  const lookup = (dict: Dict): string | undefined => {
    const value = key.split('.').reduce<string | Dict | undefined>(
      (node, part) => (node && typeof node === 'object' ? (node as Dict)[part] : undefined),
      dict,
    );
    return typeof value === 'string' ? value : undefined;
  };
  // Repli sur le français, puis sur la clé elle-même pour rendre une traduction manquante visible.
  const template = lookup(translations[language] as unknown as Dict) ?? lookup(translations.fr as unknown as Dict) ?? key;
  if (!vars) return template;
  // Pluriel « {n:démarche|démarches} » selon les règles de la langue (en français, 0 et 1 sont au singulier).
  const plurals = new Intl.PluralRules(language === 'ar' ? 'ar' : language === 'en' ? 'en' : 'fr');
  return template
    .replace(/\{(\w+):([^|{}]*)\|([^{}]*)\}/g, (_, name: string, one: string, other: string) =>
      plurals.select(Number(vars[name] ?? 0)) === 'one' ? one : other)
    .replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`));
}

/** Compatibilité avec les pages existantes (about, credits, accessibility). */
export const getTranslation = (language: Language, key: string) => translate(language, key);

/** « 1 jour », « 10 jours », « 1 day », « 3 أيام » : pluriel correct dans chaque langue (au lieu de « jour(s) »). */
export function formatDays(language: Language, count: number): string {
  const locale = language === 'ar' ? 'ar-TD' : language === 'en' ? 'en-GB' : 'fr-FR';
  return new Intl.NumberFormat(locale, { style: 'unit', unit: 'day', unitDisplay: 'long' }).format(count);
}

export function formatDate(language: Language, value: string | Date): string {
  const locale = language === 'ar' ? 'ar-TD' : language === 'en' ? 'en-GB' : 'fr-FR';
  // Une date seule (« 2026-11-01 ») est lue en heure locale : sinon elle recule d'un jour à l'ouest de Greenwich.
  const dateOnly = typeof value === 'string' ? /^(\d{4})-(\d{2})-(\d{2})$/.exec(value) : null;
  const date = dateOnly ? new Date(Number(dateOnly[1]), Number(dateOnly[2]) - 1, Number(dateOnly[3])) : new Date(value);
  return date.toLocaleDateString(locale, { day: 'numeric', month: 'long', year: 'numeric' });
}
